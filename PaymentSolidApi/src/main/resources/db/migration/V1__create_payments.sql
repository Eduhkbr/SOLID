CREATE TABLE PAYMENTS (
    ID UUID PRIMARY KEY,
    AMOUNT NUMERIC(19,2) NOT NULL CHECK (AMOUNT > 0),
    STATUS VARCHAR(50) NOT NULL CHECK (STATUS IN ('PENDING', 'REFUNDED')),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    PAYMENT_METHOD VARCHAR(50) NOT NULL CHECK (PAYMENT_METHOD IN ('PIX', 'CREDIT_CARD', 'BOLETO'))
);
